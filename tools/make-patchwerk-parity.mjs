#!/usr/bin/env node
/* Record a PATCHWERK SCORING PARITY CORPUS from the web implementation.
 *
 * WHY THIS FILE EXISTS
 * The native iOS Patchwerk (ios/Packages/MQPatchwerk) re-implements the scoring
 * state machine in Swift so a run can be driven by a clock and tested in
 * milliseconds. Two implementations of one leaderboard's arithmetic is exactly
 * the situation where a 1-damage drift makes web and iOS scores incomparable
 * without anybody noticing. So the WEB is the reference: this tool drives
 * `js/modes/patchwerk.js` over 300 scripted runs and records, for every single
 * answer, what the web produced - damage, stacks, freeze events, stun, enrage
 * flag, the ignored/swallowed decision - plus the end-of-run leaderboard record
 * and the full final state. The Swift suite replays the same scripts and must
 * reproduce every field exactly.
 *
 * ROUTE TAKEN (recorded for the lane note): NO extraction was needed.
 * `js/modes/patchwerk.js` already separates a pure `createRun()` core - no DOM,
 * no timers, no globals - from the mode object that talks to the shell, and it
 * already `module.exports`es itself for node. So this tool requires the shipped
 * file directly. Nothing was copied, nothing was refactored, and the corpus is
 * therefore a recording of THE code the web runs rather than of a fork of it.
 * (`js/modes/*` is excluded from the engine bundle by tools/build-engine.mjs, so
 * no allowlist change was needed either.)
 *
 * DETERMINISM. The scripts are generated by a seeded mulberry32, the same PRNG
 * the mode's own self-test uses. Regenerating with the same seed reproduces the
 * file byte for byte, so a corpus diff means the SCORING changed.
 *
 *   node tools/make-patchwerk-parity.mjs            -> tools/fixtures/patchwerk-parity.json
 *   node tools/make-patchwerk-parity.mjs --check    -> non-zero if the committed
 *                                                      corpus is not what today's
 *                                                      patchwerk.js produces
 */
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import path from "node:path";
import fs from "node:fs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const SOURCE = path.join(ROOT, "js", "modes", "patchwerk.js");
const OUT = path.join(ROOT, "tools", "fixtures", "patchwerk-parity.json");

const require = createRequire(import.meta.url);
const mode = require(SOURCE);
const CONFIG = mode.config;

const SEED = 20260907;
const RUNS = 300;

/* The mode's own PRNG, so the corpus and the mode's self-test speak one dialect. */
function mulberry32(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const TIER_IDS = ["short", "normal", "long"];

/* ------------------------------------------------------------------ *
 * Script generation. A script is a list of answers; each answer is a  *
 * (elapsedMs, correct, level, answerMs) tuple. The point of a corpus  *
 * is COVERAGE OF THE DECISIONS, so the shapes below are deliberate:   *
 * stun swallows, expiry swallows, the enrage boundary to the exact ms,*
 * the stack cap, the freeze cap, and unknown difficulty pools.        *
 * ------------------------------------------------------------------ */

function scriptedRuns(rand) {
  const out = [];
  const dur = (t) => CONFIG.TIERS[t].durationMs;

  /* 1-3: all correct at three speeds - caps both stacks (10) and freezes (2),
     and the third crosses the enrage boundary while capped. */
  for (const [i, gap] of [1500, 4000, 9000].entries()) {
    const tier = TIER_IDS[i % 3];
    const answers = [];
    for (let t = gap; t < dur(tier) + 3 * gap; t += gap) {
      answers.push({ elapsedMs: t, correct: true, level: (i % 3) + 1, answerMs: Math.min(gap, 11000) });
    }
    out.push({ tier, note: "all correct, " + gap + " ms cadence", answers });
  }

  /* 4: alternating right/wrong - stacks never survive, a freeze is never banked
     (earn progress resets on ANY wrong), every wrong opens a stun. */
  {
    const answers = []; let t = 0, right = true;
    while (t < dur("short") + 8000) { t += 4000; answers.push({ elapsedMs: t, correct: right, level: 1, answerMs: 4000 }); right = !right; }
    out.push({ tier: "short", note: "alternating, no freeze ever banked", answers });
  }

  /* 5: five correct, one wrong (the freeze absorbs it), recover - the design
     note's worked example, as a script. */
  {
    const answers = []; let t = 0;
    for (let i = 0; i < 5; i++) { t += 3000; answers.push({ elapsedMs: t, correct: true, level: 3, answerMs: 3000 }); }
    t += 3000; answers.push({ elapsedMs: t, correct: false, level: 3, answerMs: 3000 });
    t += 2000; for (let i = 0; i < 9; i++) { answers.push({ elapsedMs: t, correct: true, level: 3, answerMs: 2500 }); t += 3000; }
    out.push({ tier: "normal", note: "bank a freeze, eat one wrong, recover", answers });
  }

  /* 6: mashing inside the stun window. Every submission between the wrong
     answer and +1500 ms must be swallowed whole. */
  {
    const answers = []; let t = 0;
    for (let block = 0; block < 12; block++) {
      for (let i = 0; i < 3; i++) { t += 2500; answers.push({ elapsedMs: t, correct: true, level: 2, answerMs: 2500 }); }
      t += 2500; answers.push({ elapsedMs: t, correct: false, level: 2, answerMs: 2500 });
      for (const d of [1, 200, 700, 1400, 1499, 1500, 1501]) {
        answers.push({ elapsedMs: t + d, correct: true, level: 2, answerMs: 120 });
      }
      t += 4000;
    }
    out.push({ tier: "short", note: "mashing inside the 1.5 s stun", answers });
  }

  /* 7: freeze cap. Ten correct banks two credits; the next five correct must
     not bank a third. Then two wrongs spend both, a third breaks the stacks. */
  {
    const answers = []; let t = 0;
    for (let i = 0; i < 15; i++) { t += 2000; answers.push({ elapsedMs: t, correct: true, level: 2, answerMs: 1800 }); }
    for (let i = 0; i < 3; i++) { t += 3000; answers.push({ elapsedMs: t, correct: false, level: 2, answerMs: 1800 }); }
    for (let i = 0; i < 6; i++) { t += 2000; answers.push({ elapsedMs: t, correct: true, level: 2, answerMs: 1800 }); }
    out.push({ tier: "normal", note: "freeze cap at 2, then spend both", answers });
  }

  /* 8-10: the enrage boundary, to the millisecond, on every tier. */
  for (const tier of TIER_IDS) {
    const D = dur(tier), W = CONFIG.ENRAGE_WINDOW_MS;
    const answers = [];
    for (const t of [D - W - 2, D - W - 1, D - W, D - W + 1, D - W + 2,
                     D - 5000, D - 2, D - 1, D, D + 1, D + 5000]) {
      answers.push({ elapsedMs: t, correct: true, level: 1, answerMs: 9000 });
    }
    out.push({ tier, note: "enrage boundary and expiry, exact ms", answers });
  }

  /* 11-13: speed-bonus boundaries on every tier (0, 1999, 2000, 2001, 7999,
     8000, 8001, and a non-finite answerMs the shell can produce). */
  for (const tier of TIER_IDS) {
    const answers = []; let t = 0;
    for (const ms of [0, 1, 1999, 2000, 2001, 4000, 5000, 7999, 8000, 8001, 20000, null]) {
      t += 3000; answers.push({ elapsedMs: t, correct: true, level: 2, answerMs: ms });
    }
    out.push({ tier, note: "speed bonus boundaries", answers });
  }

  /* 14: unknown difficulty pools - BASE_DAMAGE_FALLBACK. */
  {
    const answers = []; let t = 0;
    for (const level of [0, 1, 2, 3, 4, 9, null, 2, 3]) {
      t += 2500; answers.push({ elapsedMs: t, correct: true, level, answerMs: 2500 });
    }
    out.push({ tier: "short", note: "unknown pools fall back to BASE_DAMAGE_FALLBACK", answers });
  }

  /* 15: nothing at all. A run can end with no answers in it. */
  out.push({ tier: "normal", note: "no answers", answers: [] });

  /* 16: one answer, at t=0 exactly. */
  out.push({ tier: "short", note: "single answer at t=0", answers: [{ elapsedMs: 0, correct: true, level: 2, answerMs: 0 }] });

  /* 17: every answer wrong. Stacks stay at 0, damage stays at 0, and the stun
     eats most of the follow-ups. */
  {
    const answers = []; let t = 0;
    for (let i = 0; i < 40; i++) { t += 2000; answers.push({ elapsedMs: t, correct: false, level: 3, answerMs: 2000 }); }
    out.push({ tier: "short", note: "every answer wrong", answers });
  }

  /* 18: a long heroic run at a realistic cadence, the shape a strong child
     actually plays. */
  {
    const answers = []; let t = 0;
    for (let i = 0; t < dur("long"); i++) {
      const wrong = i % 9 === 8;
      t += wrong ? 5200 : 3400;
      answers.push({ elapsedMs: t, correct: !wrong, level: i % 3 === 0 ? 1 : (i % 3 === 1 ? 2 : 3), answerMs: wrong ? 6000 : 2600 });
    }
    out.push({ tier: "long", note: "realistic heroic run", answers });
  }

  /* 19: answers strictly after expiry only. */
  {
    const D = dur("short");
    out.push({
      tier: "short", note: "everything after expiry",
      answers: [D, D + 1, D + 1000, D + 60000].map((t) => ({ elapsedMs: t, correct: true, level: 3, answerMs: 500 }))
    });
  }

  /* 20: out-of-order timestamps. The mode does not sort; it takes elapsedMs as
     given, and the Swift port must be just as literal about it. */
  {
    const answers = [
      { elapsedMs: 10000, correct: true, level: 2, answerMs: 2000 },
      { elapsedMs: 9000, correct: true, level: 2, answerMs: 2000 },
      { elapsedMs: 30000, correct: false, level: 2, answerMs: 2000 },
      { elapsedMs: 25000, correct: true, level: 2, answerMs: 2000 },
      { elapsedMs: 31000, correct: true, level: 2, answerMs: 2000 }
    ];
    out.push({ tier: "normal", note: "out-of-order timestamps", answers });
  }

  /* The rest: randomised, with per-run accuracy and cadence. */
  while (out.length < RUNS) {
    const i = out.length;
    const tier = TIER_IDS[i % 3];
    const D = CONFIG.TIERS[tier].durationMs;
    const acc = 0.5 + rand() * 0.48;
    const answers = [];
    let t = 0;
    while (t < D + 6000 && answers.length < 400) {
      const r = rand();
      /* One in eight gaps is short enough to land inside a stun window. */
      const gap = r < 0.125 ? Math.floor(200 + rand() * 1300)
                            : Math.floor(1200 + rand() * 5200);
      t += gap;
      const correct = rand() < acc;
      const level = 1 + Math.floor(rand() * 3);
      const answerMs = rand() < 0.08 ? [0, 2000, 8000, 12000][Math.floor(rand() * 4)]
                                     : Math.floor(200 + rand() * 9000);
      answers.push({ elapsedMs: t, correct, level, answerMs });
    }
    out.push({ tier, note: "randomised, accuracy " + acc.toFixed(3), answers });
  }

  return out.slice(0, RUNS);
}

/* ------------------------------------------------------------------ *
 * Recording. Everything observable, per answer.                       *
 * ------------------------------------------------------------------ */

/* Positional encoding, declared in the corpus header and read by both runtimes.
   Named keys on 17,682 events cost 3 MB of repository in field names alone; the
   field ORDER is the contract instead, and it is asserted on the Swift side. */
const ANSWER_FIELDS = ["elapsedMs", "correct", "level", "answerMs"];
const EVENT_FIELDS = [
  /* the event the mode returned */
  "ignored", "correct", "damage", "stacks", "froze", "earnedFreeze", "stunMs", "enraged",
  /* and the whole machine's state AFTER it - a per-answer fingerprint */
  "totalDamage", "heldStacks", "maxStacks", "correctCount", "wrongCount",
  "freezes", "freezesUsed", "earnProgress", "stunUntilMs", "bossHp", "bossPhase"
];
const b = (v) => (v ? 1 : 0);

function recordRun(script, index) {
  const run = mode.createRun({ tier: script.tier });
  const events = [];
  for (const a of script.answers) {
    const meta = { level: a.level === null ? undefined : a.level, elapsedMs: a.elapsedMs };
    if (a.answerMs !== null && a.answerMs !== undefined) meta.answerMs = a.answerMs;
    const ev = run.applyAnswer(a.correct, meta);
    const st = run.state();
    events.push([
      b(ev.ignored), b(ev.correct), ev.damage, ev.stacks, b(ev.froze), b(ev.earnedFreeze),
      ev.stunMs, b(ev.enraged),
      st.damage, st.stacks, st.maxStacks, st.correct, st.wrong,
      st.freezes, st.freezesUsed, st.earnProgress, st.stunUntilMs, st.bossHp, st.bossPhase
    ]);
  }
  const level = 1 + (index % 3);
  const record = run.finish(CONFIG.TIERS[script.tier].durationMs, { level, date: "2026-09-07" });
  const st = run.state();
  return {
    id: index,
    tier: script.tier,
    durationMs: CONFIG.TIERS[script.tier].durationMs,
    note: script.note,
    recordLevel: level,
    answers: script.answers.map((a) => [
      a.elapsedMs, b(a.correct),
      a.level === null || a.level === undefined ? null : a.level,
      a.answerMs === null || a.answerMs === undefined ? null : a.answerMs
    ]),
    events,
    record,
    finalState: {
      damage: st.damage, stacks: st.stacks, maxStacks: st.maxStacks,
      correct: st.correct, wrong: st.wrong, freezes: st.freezes,
      freezesUsed: st.freezesUsed, earnProgress: st.earnProgress,
      stunUntilMs: st.stunUntilMs, bossHp: st.bossHp, bossPhase: st.bossPhase,
      enraged: st.enraged, ended: st.ended
    }
  };
}

function build() {
  const rand = mulberry32(SEED);
  const scripts = scriptedRuns(rand);
  const runs = scripts.map(recordRun);
  const sourceBytes = fs.readFileSync(SOURCE);
  const answers = runs.reduce((n, r) => n + r.answers.length, 0);
  /* index 0 is `ignored` - see EVENT_FIELDS */
  const scored = runs.reduce((n, r) => n + r.events.filter((e) => e[0] === 0).length, 0);
  return {
    schema: "patchwerk-parity/1",
    generator: "tools/make-patchwerk-parity.mjs",
    source: "js/modes/patchwerk.js",
    sourceSha256: createHash("sha256").update(sourceBytes).digest("hex"),
    seed: SEED,
    runCount: runs.length,
    answerCount: answers,
    scoredAnswerCount: scored,
    answerFields: ANSWER_FIELDS,
    eventFields: EVENT_FIELDS,
    config: {
      tiers: Object.keys(CONFIG.TIERS).map((k) => ({ id: k, label: CONFIG.TIERS[k].label, durationMs: CONFIG.TIERS[k].durationMs })),
      defaultTier: CONFIG.DEFAULT_TIER,
      baseDamage: CONFIG.BASE_DAMAGE,
      baseDamageFallback: CONFIG.BASE_DAMAGE_FALLBACK,
      stackStep: CONFIG.STACK_STEP,
      stackCap: CONFIG.STACK_CAP,
      speedBonusMax: CONFIG.SPEED_BONUS_MAX,
      speedFastMs: CONFIG.SPEED_FAST_MS,
      speedZeroMs: CONFIG.SPEED_ZERO_MS,
      freezeEarnEvery: CONFIG.FREEZE_EARN_EVERY,
      freezeMaxHeld: CONFIG.FREEZE_MAX_HELD,
      stunMs: CONFIG.STUN_MS,
      enrageWindowMs: CONFIG.ENRAGE_WINDOW_MS,
      enrageMult: CONFIG.ENRAGE_MULT,
      bossHpPerPhase: CONFIG.BOSS_HP_PER_PHASE
    },
    runs
  };
}

const corpus = build();
/* Compact, one line, like tools/fixtures/parity-corpus.json: this is a machine
   fixture read by two runtimes, not a file anybody diffs by eye, and pretty
   printing it costs 5 MB of repository for nothing. */
const text = JSON.stringify(corpus) + "\n";

if (process.argv.includes("--check")) {
  if (!fs.existsSync(OUT)) {
    console.error("MISSING: " + path.relative(ROOT, OUT));
    process.exit(1);
  }
  const have = fs.readFileSync(OUT, "utf8");
  if (have !== text) {
    console.error("STALE: " + path.relative(ROOT, OUT) + " is not what js/modes/patchwerk.js produces today.");
    console.error("  Run: node tools/make-patchwerk-parity.mjs   (and commit the result)");
    process.exit(1);
  }
  console.log("patchwerk parity corpus is current: " + corpus.runCount + " runs, " +
              corpus.answerCount + " answers (" + corpus.scoredAnswerCount + " scored).");
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, text);
console.log("wrote " + path.relative(ROOT, OUT));
console.log("  runs            " + corpus.runCount);
console.log("  answers         " + corpus.answerCount + " (" + corpus.scoredAnswerCount + " scored, " +
            (corpus.answerCount - corpus.scoredAnswerCount) + " swallowed)");
console.log("  source sha256   " + corpus.sourceSha256.slice(0, 16));
